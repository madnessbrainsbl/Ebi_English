def import_all():
    with closing(sqlite3.connect(DATABASE_PATH)) as conn, conn:
        conn.execute(
            "CREATE TABLE IF NOT EXISTS content_sources (name TEXT PRIMARY KEY, url TEXT NOT NULL, license TEXT NOT NULL)"
        )
        for source in SOURCES:
            conn.execute(
                "INSERT OR REPLACE INTO content_sources (name, url, license) VALUES (?, ?, ?)",
                source,
            )

        for deck in DECKS:
            conn.execute("DELETE FROM cards WHERE deck_id = ?", (deck[0],))
            conn.execute("DELETE FROM decks WHERE id = ?", (deck[0],))
            conn.execute(
                "INSERT INTO decks (id, name, icon, is_grammar, cefr, ladder_pos) VALUES (?, ?, ?, ?, ?, ?)",
                deck,
            )

        deck_map = {
            "LIB_IRREG_A2": IRREGULAR_A2,
            "LIB_IRREG_B1": IRREGULAR_B1,
            "LIB_PHRASAL_B1": PHRASAL_B1,
            "LIB_PHRASAL_B2": PHRASAL_B2,
        }

        for deck_id, cards in deck_map.items():
            conn.executemany(
                "INSERT INTO cards (deck_id, en, ru, example, tip, sort_order) VALUES (?, ?, ?, ?, ?, ?)",
                [
                    (deck_id, item[0], item[1], item[2], item[3], idx)
                    for idx, item in enumerate(cards)
                ],
            )

    encoded = base64.b64encode(DATABASE_PATH.read_bytes()).decode("ascii")
    EMBEDDED_DATABASE_PATH.write_text(
        f'const CONTENT_DB_B64="{encoded}";\n', encoding="ascii"
    )
    print(f"Imported {sum(len(c) for c in deck_map.values())} cards across {len(deck_map)} decks successfully.")


if __name__ == "__main__":
    import_all()
